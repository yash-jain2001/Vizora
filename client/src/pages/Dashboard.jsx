  useEffect(() => {
    const fetchDatasources = async () => {
      try {
        const res = await API.get('/datasources');
        setDatasources(res.data);
      } catch (error) {
        console.error("Error fetching datasources:", error);
      }
    };
    fetchDatasources();
  }, []);

