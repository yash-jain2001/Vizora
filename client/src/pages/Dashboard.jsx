  const saveDashboard = async () => {
    try {
      await API.put(`/dashboards/${id}`, {
        title: dashboardTitle,
        widgets,
      });
      alert('Dashboard saved successfully!');
    } catch (error) {
      console.log(error);
      alert('Failed to save dashboard.');
    }
  };

